<h1>Selamat Datang</h1>

<p>
    Gagasan pendirian Jurusan Teknologi Informasi sudah ada sejak awal tahun 2000, 
    namun terkendala oleh beberapa pertimbangan, antara lain ketersediaan Sumber Daya Manusia 
    dan infrastruktur.
</p>

<p>
    Pada awal bulan Februari 2005, beberapa orang dosen yang antara lain terdiri dari 
    Erwadi Bakar, Surfayondri, Andrizal, H. A. Mooduto, Yulindon, Ahmad Dahlan, 
    Ronal Hadi, dan Rahmat Hidayat, atas dukungan yang kuat dari pimpinan 
    Politeknik Suhendrik Hanwar serta pimpinan lainnya, menyusun proposal 
    pendirian program studi yang berkaitan dengan Teknologi Informasi.
</p>

<p>
    Dasar utama pendirian jurusan ini adalah keinginan Politeknik Unand Padang 
    untuk ikut berkontribusi secara maksimal dalam pengembangan dan penerapan 
    teknologi informasi melalui dunia pendidikan, serta sebagai langkah antisipasi 
    terhadap perkembangan teknologi informasi dan komunikasi yang sangat pesat 
    dan membutuhkan sumber daya manusia yang kompeten.
</p>

<p>
    Program studi yang diusulkan pada waktu itu adalah Teknik Komputer, 
    Teknik Informatika, dan Manajemen Informatika. Alhamdulillah, dalam waktu 
    yang tidak terlalu lama, izin pendirian program studi ini disetujui oleh DIKTI 
    untuk dua program studi, yaitu Teknik Komputer dan Manajemen Informatika. 
    Hal ini merupakan bukti kepercayaan DIKTI kepada Politeknik Unand Padang.
</p>

<p>
    Penerimaan mahasiswa baru angkatan pertama dilaksanakan pada bulan 
    September 2005, meskipun terlambat dua minggu dibandingkan dengan jurusan lainnya. 
    Atas kesepakatan tim, pada tahap awal pengelolaan jurusan ini dipercayakan kepada 
    Erwadi Bakar sebagai Ketua Jurusan dan Ronal Hadi sebagai Sekretaris Jurusan.
</p>
